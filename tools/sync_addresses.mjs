/**
 * Writes frontend/src/lib/deployments.ts and ADDRESSES.md from
 * deployments.json - the ONE set of addresses used everywhere.
 *   node tools/sync_addresses.mjs [--set=smoke]
 */
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("..", import.meta.url).pathname;
const set = (process.argv.find((a) => a.startsWith("--set=")) ?? "--set=final").slice(6);
const file = set === "final" ? "deployments.json" : `deployments.${set}.json`;
const d = JSON.parse(readFileSync(root + file, "utf8"));
const c = d.contracts;
const map = {
  execReader: c.ExecReader, voteReader: c.VoteReader, judge: c.AsVotedJudge, registry: c.AsVotedRegistry,
  registryDemo: c.AsVotedRegistryDemo, standing: c.DaoStanding, standingDemo: c.DaoStandingDemo, gate: c.GrantGate, gateDemo: c.GrantGateDemo,
};
const lines = Object.entries(map).map(([k, v]) => `  ${k}: "${v.address.toLowerCase()}",`).join("\n");
const commits = [...new Set(Object.values(c).map((v) => v.commit))];
writeFileSync(root + "frontend/src/lib/deployments.ts", `// Generated by tools/sync_addresses.mjs from ${file}. Do not edit.
export const ADDR = {
${lines}
} as const;

export const DEPLOY_COMMIT = "${commits[0]}";
export const DEPLOYMENTS = ${JSON.stringify(Object.fromEntries(Object.entries(c).map(([k, v]) => [k, { address: v.address.toLowerCase(), file: v.file, commit: v.commit, sha256: v.sha256, bytes: v.bytes, deploy_tx: v.deploy_tx, constructor_args: v.constructor_args, mode: v.mode ?? "" }])), null, 2)} as const;
`);
const md = ["# Addresses (GenLayer Studio Dev, chain 61997)", "", `Every contract below was deployed from commit \`${commits.join(", ")}\`. \`tools/verify_source.mjs\` reads each one back with \`gen_getContractCode\` and compares it byte for byte with that commit.`, "",
  "| Contract | Address | Source | sha256 | Constructor |", "|---|---|---|---|---|",
  ...Object.entries(c).map(([k, v]) => `| ${k} | [\`${v.address}\`](https://explorer-studio-dev.genlayer.com/address/${v.address}) | \`${v.file}\` | \`${v.sha256.slice(0, 16)}…\` | \`${JSON.stringify(v.constructor_args)}\` |`), ""];
if (set === "final") writeFileSync(root + "ADDRESSES.md", md.join("\n"));
console.log(`wrote deployments.ts from ${file} (${Object.keys(c).length} contracts, commits ${commits.join(",")})`);
